// 镜头路线：每一站 = [机位, 注视点, 视角(fov), 侧倾(roll)]。
// 滚动进度 u ∈ [0,1] 均匀地分布在各站之间，用 Catmull-Rom 曲线平滑插值，
// 机位、朝向、视角、侧倾一起变化，所以镜头会绕行、横移、转向，而不是直线推进。
export const STOPS = [
  // 0 开场：低机位广角，斜着看向远处的废墟和教堂
  [[150, 15, 660], [-40, 46, -120], 62, -0.08],
  // 1 降到水面附近，转向第一道巨门
  [[66, 6.5, 486], [-4, 34, 230], 54, -0.025],
  // 2 穿过第一道巨门
  [[6, 3.6, 338], [6, 24, 150], 60, 0],
  // 3 横移到左侧拱廊下，仰看右侧
  [[-24, 4.0, 214], [16, 30, 70], 52, 0.02],
  // 4 横移到右侧，侧身看向左前方
  [[16, 3.4, 128], [-20, 26, -30], 56, -0.012],
  // 5 穿过第二道巨门，教堂第一次完整出现
  [[-4, 4.6, 26], [0, 32, -140], 48, 0],
  // 6 接近教堂，仰视正立面
  [[0, 6.4, -76], [0, 24, -150], 54, 0],
  // 7 站在门洞里
  [[0, 5.6, -131], [0, 9.5, -230], 58, 0],
  // 8 主厅中段
  [[0, 5.6, -184], [0, 11, -300], 64, 0],
  // 9 终点：主厅前部，四个栏目物件就在眼前
  [[0, 5.3, -238], [0, 8.6, -300], 60, 0],
];

const cr = (a, b, c, d, t) =>
  0.5 * (2 * b + (c - a) * t + (2 * a - 5 * b + 4 * c - d) * t * t + (3 * b - a - 3 * c + d) * t * t * t);

export function sample(u) {
  const N = STOPS.length - 1;
  const x = Math.min(Math.max(u, 0), 1) * N;
  const i = Math.min(Math.floor(x), N - 1);
  const t = x - i;
  const S = (k) => STOPS[Math.max(0, Math.min(N, k))];
  const a = S(i - 1), b = S(i), c = S(i + 1), d = S(i + 2);
  const v = (j) => [0, 1, 2].map((k) => cr(a[j][k], b[j][k], c[j][k], d[j][k], t));
  return {
    pos: v(0),
    tgt: v(1),
    fov: cr(a[2], b[2], c[2], d[2], t),
    roll: cr(a[3], b[3], c[3], d[3], t),
  };
}

// 路线在水平面上的采样点，用来让十字架等物体避开镜头
export function pathXZ(n = 400) {
  const out = [];
  for (let i = 0; i <= n; i++) {
    const s = sample(i / n);
    out.push([s.pos[0], s.pos[2]]);
  }
  return out;
}
